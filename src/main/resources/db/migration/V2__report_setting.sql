-- 보고서별 사용자 설정(서식과 미리보기)
-- 사용자를 삭제하면 그 사용자의 설정도 함께 지운다.
CREATE TABLE REPORT_SETTING (
    USER_ID            VARCHAR(100) NOT NULL,
    REPORT_TYPE        VARCHAR(30)  NOT NULL,
    FONT_FAMILY        VARCHAR(20)  NOT NULL,
    FONT_SIZE_STEP     INTEGER      NOT NULL,
    LINE_SPACING       INTEGER      NOT NULL,
    AUTO_FIT           BOOLEAN      NOT NULL,
    THUMBNAILS_VISIBLE BOOLEAN      NOT NULL,
    VIEW_MODE          VARCHAR(20)  NOT NULL,
    ZOOM_MODE          VARCHAR(20)  NOT NULL,
    ZOOM_PERCENT       INTEGER      NOT NULL,
    CONSTRAINT PK_REPORT_SETTING PRIMARY KEY (USER_ID, REPORT_TYPE),
    CONSTRAINT FK_REPORT_SETTING_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID) ON DELETE CASCADE
);
