-- 최초 스키마
-- 엔터티의 매핑과 일치해야 한다(ddl-auto: validate가 기동할 때 확인한다).
-- enum은 상수를 추가할 때 스키마를 바꾸지 않아도 되도록 VARCHAR로 저장하고, 허용 값을 제약으로 묶지 않는다.
-- H2는 외래 키마다 참조하는 칼럼의 인덱스를 자동으로 만들므로, 인덱스는 조회 조건과 정렬에 맞춘 복합 인덱스만 따로 만든다.

-- 사용자
CREATE TABLE USERS (
    ID                 VARCHAR(100) NOT NULL,
    PASSWORD           VARCHAR(255) NOT NULL,
    IS_PASSWORD_CHAGED BOOLEAN      NOT NULL,
    ROLE               VARCHAR(10)  NOT NULL,
    REMARKS            VARCHAR(100),
    CONSTRAINT PK_USERS PRIMARY KEY (ID)
);

-- 사용자 설정. 선택한 회계 연도는 삭제되어도 남을 수 있으므로 외래 키로 묶지 않는다.
CREATE TABLE USER_SETTINGS (
    USER_ID                 VARCHAR(100) NOT NULL,
    SELECTED_FISCAL_YEAR_ID BIGINT,
    CONSTRAINT PK_USER_SETTINGS PRIMARY KEY (USER_ID),
    CONSTRAINT FK_USER_SETTINGS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID)
);

-- 회계 연도
CREATE TABLE FISCAL_YEAR (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    NAME          VARCHAR(30) NOT NULL,
    START_DATE    DATE        NOT NULL,
    END_DATE      DATE        NOT NULL,
    CLOSED        BOOLEAN     NOT NULL,
    TOTAL_INCOME  BIGINT,
    TOTAL_EXPENSE BIGINT,
    BALANCE       BIGINT,
    CONSTRAINT PK_FISCAL_YEAR PRIMARY KEY (ID),
    CONSTRAINT UK_FISCAL_YEAR_NAME UNIQUE (NAME)
);

-- 예산
CREATE TABLE BUDGET (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    FISCAL_YEAR_ID BIGINT      NOT NULL,
    TYPE           VARCHAR(10) NOT NULL,
    PARENT_ID      BIGINT,
    NAME           VARCHAR(50) NOT NULL,
    AMOUNT         BIGINT,
    SORT_ORDER     INTEGER     NOT NULL,
    CONSTRAINT PK_BUDGET PRIMARY KEY (ID),
    CONSTRAINT FK_BUDGET_FISCAL_YEAR FOREIGN KEY (FISCAL_YEAR_ID) REFERENCES FISCAL_YEAR (ID),
    CONSTRAINT FK_BUDGET_PARENT FOREIGN KEY (PARENT_ID) REFERENCES BUDGET (ID)
);

-- 같은 상위 예산 아래의 예산을 순서대로 조회하고, 그 마지막 순서를 찾는다.
CREATE INDEX IX_BUDGET_FISCAL_YEAR_PARENT_SORT_ORDER ON BUDGET (FISCAL_YEAR_ID, PARENT_ID, SORT_ORDER);

-- 관계자
CREATE TABLE CONTACT (
    ID        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    TYPE      VARCHAR(30)  NOT NULL,
    NAME      VARCHAR(100) NOT NULL,
    REMARKS   VARCHAR(100),
    IS_HIDDEN BOOLEAN      NOT NULL,
    CONSTRAINT PK_CONTACT PRIMARY KEY (ID)
);

-- 관계자 목록과 자동 완성은 이름순이다.
CREATE INDEX IX_CONTACT_NAME ON CONTACT (NAME);

-- 관계자 그룹
CREATE TABLE CONTACT_GROUP (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT PK_CONTACT_GROUP PRIMARY KEY (ID)
);

CREATE TABLE CONTACT_GROUP_MEMBER (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    CONTACT_GROUP_ID BIGINT  NOT NULL,
    CONTACT_ID       BIGINT  NOT NULL,
    ORDER_INDEX      INTEGER NOT NULL,
    CONSTRAINT PK_CONTACT_GROUP_MEMBER PRIMARY KEY (ID),
    CONSTRAINT FK_CONTACT_GROUP_MEMBER_GROUP FOREIGN KEY (CONTACT_GROUP_ID) REFERENCES CONTACT_GROUP (ID),
    CONSTRAINT FK_CONTACT_GROUP_MEMBER_CONTACT FOREIGN KEY (CONTACT_ID) REFERENCES CONTACT (ID)
);

-- 그룹의 구성원을 순서대로 조회한다.
CREATE INDEX IX_CONTACT_GROUP_MEMBER_GROUP_ORDER_INDEX ON CONTACT_GROUP_MEMBER (CONTACT_GROUP_ID, ORDER_INDEX);

-- 수입/지출
CREATE TABLE FINANCIAL_RECORD (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    TYPE           VARCHAR(10)  NOT NULL,
    FISCAL_YEAR_ID BIGINT       NOT NULL,
    DATE           DATE         NOT NULL,
    BUDGET_ID      BIGINT       NOT NULL,
    DESCRIPTION    VARCHAR(100),
    AMOUNT         BIGINT       NOT NULL,
    REMARKS        VARCHAR(100),
    CONSTRAINT PK_FINANCIAL_RECORD PRIMARY KEY (ID),
    CONSTRAINT FK_FINANCIAL_RECORD_FISCAL_YEAR FOREIGN KEY (FISCAL_YEAR_ID) REFERENCES FISCAL_YEAR (ID),
    CONSTRAINT FK_FINANCIAL_RECORD_BUDGET FOREIGN KEY (BUDGET_ID) REFERENCES BUDGET (ID)
);

-- 회계 연도의 내역을 날짜순으로 조회하고, 기간으로 검색하고, 가장 이른/늦은 날짜를 찾는다.
CREATE INDEX IX_FINANCIAL_RECORD_FISCAL_YEAR_DATE ON FINANCIAL_RECORD (FISCAL_YEAR_ID, DATE);
-- 회계 연도의 수입 또는 지출 금액을 예산별로 더한다(마감, 대시보드, 보고서, 예산 진행 현황).
CREATE INDEX IX_FINANCIAL_RECORD_FISCAL_YEAR_TYPE_BUDGET ON FINANCIAL_RECORD (FISCAL_YEAR_ID, TYPE, BUDGET_ID);

-- 수입/지출의 관계자(봉헌자, 수취인). 이름은 기록 당시의 이름이다.
CREATE TABLE FINANCIAL_RECORD_CONTACT (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    FINANCIAL_RECORD_ID BIGINT       NOT NULL,
    CONTACT_ID          BIGINT       NOT NULL,
    CONTACT_NAME        VARCHAR(100) NOT NULL,
    CONSTRAINT PK_FINANCIAL_RECORD_CONTACT PRIMARY KEY (ID),
    CONSTRAINT FK_FINANCIAL_RECORD_CONTACT_RECORD FOREIGN KEY (FINANCIAL_RECORD_ID) REFERENCES FINANCIAL_RECORD (ID),
    CONSTRAINT FK_FINANCIAL_RECORD_CONTACT_CONTACT FOREIGN KEY (CONTACT_ID) REFERENCES CONTACT (ID)
);

-- 관계자(가족 등 여러 명)로 내역을 검색한다. 내역 ID까지 담아 표를 읽지 않고 인덱스만으로 내역 ID를 찾는다.
CREATE INDEX IX_FINANCIAL_RECORD_CONTACT_CONTACT_RECORD ON FINANCIAL_RECORD_CONTACT (CONTACT_ID, FINANCIAL_RECORD_ID);

-- 활동 기록. 사용자가 삭제되어도 기록은 남아야 하므로 사용자 ID를 외래 키로 묶지 않는다.
CREATE TABLE ACTIVITY_LOG (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    USER_ID       VARCHAR(255) NOT NULL,
    ACTIVITY_TYPE VARCHAR(20)  NOT NULL,
    TARGET_NAME   VARCHAR(255) NOT NULL,
    DESCRIPTION   CLOB         NOT NULL,
    CREATED_AT    TIMESTAMP(6) NOT NULL,
    CONSTRAINT PK_ACTIVITY_LOG PRIMARY KEY (ID)
);

-- 활동 기록은 계속 쌓이며, 기간으로 검색해 최근 것부터 보여준다.
CREATE INDEX IX_ACTIVITY_LOG_CREATED_AT ON ACTIVITY_LOG (CREATED_AT DESC);
